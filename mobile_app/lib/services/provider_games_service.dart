import 'dart:convert';
import 'package:flutter_secure_storage/flutter_secure_storage.dart';

enum ProviderStatus {
  authorizedActive,
  pendingCredentials,
  maintenance,
}

class ProviderGame {
  final String id;
  final String title;
  final String provider;
  final String category; // 'slots', 'live', 'fishing', 'poker', 'lottery', 'sports', 'crash', 'prediction', 'mini', 'cards'
  final String engineIdentifier;
  final String description;
  final String? launchUrl;
  final String rtp;
  final bool isOfficiallyAuthorized;
  final ProviderStatus status;
  final String licensingInfo;
  final String requiredCredentials;
  final String iconName;
  final String badgeText;

  const ProviderGame({
    required this.id,
    required this.title,
    required this.provider,
    required this.category,
    required this.engineIdentifier,
    required this.description,
    this.launchUrl,
    required this.rtp,
    required this.isOfficiallyAuthorized,
    required this.status,
    required this.licensingInfo,
    required this.requiredCredentials,
    required this.iconName,
    required this.badgeText,
  });

  Map<String, dynamic> toJson() => {
    'id': id,
    'title': title,
    'provider': provider,
    'category': category,
    'engineIdentifier': engineIdentifier,
    'description': description,
    'launchUrl': launchUrl,
    'rtp': rtp,
    'isOfficiallyAuthorized': isOfficiallyAuthorized,
    'status': status.name,
    'licensingInfo': licensingInfo,
    'requiredCredentials': requiredCredentials,
    'iconName': iconName,
    'badgeText': badgeText,
  };
}

class ProviderConfig {
  final String providerName;
  final String status;
  final bool isConfigured;
  final String? operatorCode;
  final String? apiKey;
  final String? secretKey;
  final String? endpointUrl;
  final DateTime? lastChecked;

  const ProviderConfig({
    required this.providerName,
    required this.status,
    required this.isConfigured,
    this.operatorCode,
    this.apiKey,
    this.secretKey,
    this.endpointUrl,
    this.lastChecked,
  });

  Map<String, dynamic> toJson() => {
    'providerName': providerName,
    'status': status,
    'isConfigured': isConfigured,
    'operatorCode': operatorCode,
    'apiKey': apiKey,
    'secretKey': secretKey,
    'endpointUrl': endpointUrl,
    'lastChecked': lastChecked?.toIso8601String(),
  };

  factory ProviderConfig.fromJson(Map<String, dynamic> json) => ProviderConfig(
    providerName: json['providerName'] ?? '',
    status: json['status'] ?? 'Pending Setup',
    isConfigured: json['isConfigured'] ?? false,
    operatorCode: json['operatorCode'],
    apiKey: json['apiKey'],
    secretKey: json['secretKey'],
    endpointUrl: json['endpointUrl'],
    lastChecked: json['lastChecked'] != null ? DateTime.tryParse(json['lastChecked']) : null,
  );
}

